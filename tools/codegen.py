import sys 
import os
import re #regular expressions

# TODO : implement reflection for all classes; not just ones that inherit from something.
# also include the namespaces of those headers 
def gen_reflection(out_path, header_paths):

    # find classes, and everything up to the bracket after the class def {
    class_head_regex = re.compile(r'class\s+(\w+)\s*:\s*public\s+([^\{]+)\{')
    # look for members with the PUBLIC keyword in front of them
    public_regex = re.compile(r'PUBLIC\s+(\w+(?:::\w+)*)\s+(\w+)\s*(?:=.*)?\s*;')

    generated_code = """/*          GENERATED BY CMAKE CODEGEN - DO NOT TOUCH         */
#include <field_reflect.hpp>

#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Winvalid-offsetof"

using namespace Engine;
"""

    includes = ""
    # the init function! the program RELIES on this!
    bindings = "\nvoid Engine::initializeReflectionData() {\n"

    # loop through every header 
    for header in header_paths:
        if not os.path.exists(header):
            continue

        with open(header, 'r') as f:
            content = f.read()

        # look through all classes in this header (are there multiple?)
        for class_match in class_head_regex.finditer(content):
            class_name = class_match.group(1)
            
            # get inheritance stuff
            inheritance_chunk = class_match.group(2)
            
            # get just the first class (probably IComponent)
            base_name = re.split(r'[\s,]+', inheritance_chunk.strip())[0]

            # get the class contents
            start_idx = class_match.end()
            brace_count = 1
            class_body = ""
            
            for i in range(start_idx, len(content)):
                if content[i] == '{':
                    brace_count += 1
                elif content[i] == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        class_body = content[start_idx:i]
                        break
                if i == len(content) - 1:
                    class_body = content[start_idx:]

            # check if component_public is in this file
            if "component_public" not in class_body:
                continue

            # it is! this is a valid component 
            header_inc = f'#include "{os.path.abspath(header)}"\n'
            if header_inc not in includes:
                includes += header_inc

            # get the PUBLIC fields
            fields = public_regex.findall(class_body)

            # bind the component's protected typename string
            bindings += f'    {class_name}::_reflectionName = "{class_name}";\n'

            # bind the component's lambda query
            bindings += f"""    {class_name}::_reflectionFieldQuery = []() -> const std::vector<ReflectableField>& {{
        using parent = {base_name};
        static std::vector<ReflectableField> fields = []() {{
            std::vector<ReflectableField> localFields = {{
"""
            for f_type, f_name in fields:
                bindings += f'                {{ "{f_name}", offsetof({class_name}, {f_name}), "{f_type}" }},\n'
                
            bindings += """            };
            
            // Check if the parent class has fields bound to its reflection slot
            if constexpr (requires { parent::_reflectionFieldQuery; }) {
                if (parent::_reflectionFieldQuery != nullptr) {
                    const auto& parentFields = parent::_reflectionFieldQuery();
                    localFields.insert(localFields.begin(), parentFields.begin(), parentFields.end());
                }
            }
            
            return localFields;
        }();
        
        return fields;
    };

"""

    # end the namespace
    bindings += "}\n" 
    generated_code += includes + bindings + "\n#pragma GCC diagnostic pop\n"

    # write our file out.
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w') as f:
        f.write(generated_code)

if __name__ == "__main__":
    gen_reflection(sys.argv[1], sys.argv[2:])
